/**
 * PaymentBackend — the contract the on-chain integration implements.
 *
 * The MCP server (PaymentService) enforces mandates BEFORE calling any of these methods.
 * A backend only moves escrowed testnet USDC; it never decides whether a payment is allowed.
 *
 * Network: Solana devnet only. Mint: devnet USDC (DEVNET_USDC_MINT). Base/EVM is out of scope.
 *
 * Units: all amounts are USDC base units (6 decimals) as bigint. 1 USDC = 1_000_000n.
 * Times: unix seconds (number), compared against the chain clock (Clock sysvar) on capture402.
 *
 * Reference implementation: capture402-solana (github.com/starPaw/capture402-solana),
 * src/lib.rs + integration/src/transactions.ts. See INTERFACE.md for the full mapping table.
 */

/** Devnet USDC (Circle). The only mint the service accepts (QA M-2). */
export const DEVNET_USDC_MINT = "4zMMC9srt5Ri5X14GAgXhaHii3GnPAEERYPJgZJDncDU";
export const USDC_DECIMALS = 6;

/** Mandate terms as agreed by the human owner of the paying agent. Off-chain in capture402. */
export interface MandateTerms {
  id: string;
  /** Paying agent's address (capture402: payer pubkey). */
  payer: string;
  totalBudget: bigint;
  perTxCap: bigint;
  /** Unix seconds. No new holds after this; also the latest allowed captureDeadline. */
  expiresAt: number;
  /** Payee addresses (capture402: server/merchant pubkeys) this mandate may pay. */
  allowedCounterparties: string[];
}

/** capture402 `authorize` (tag 0). Moves the full `maximum` from payer ATA into the escrow vault. */
export interface HoldRequest {
  payer: string;
  /** SPL mint. Must be devnet USDC (DEVNET_USDC_MINT); the program accepts any classic mint (QA M-2). */
  mint: string;
  /** capture402: `server` — the merchant who later signs capture/void/refund. */
  payee: string;
  /** Immutable on-chain maximum. Must be > 0. */
  maximum: bigint;
  /** Unix s. Capture only while now < captureDeadline; payer may reclaim at/after it. */
  captureDeadline: number;
  /** Unix s, >= captureDeadline. Refund only while now < refundDeadline. */
  refundDeadline: number;
  /** 32-byte hex. Payment PDA = PDA(["auth-capture-v1", payer, salt]). Generated by the service. */
  salt: string;
}

export interface HoldReceipt {
  /** capture402: the payment PDA address. Used as the id for every later call. */
  holdId: string;
  /** Mock ref for MockBackend; finalized devnet transaction signature for Capture402Backend. Goes into the audit log (the program emits no logs, QA L-2). */
  txSig: string;
}

/**
 * expectedHeld / expectedRefundable are capture402's optimistic-concurrency guard:
 * the instruction fails if the on-chain Payment state differs. The service passes its last known values.
 */
interface StateGuard {
  holdId: string;
  expectedHeld: bigint;
  expectedRefundable: bigint;
}

/** capture402 `capture` (tag 2), merchant-signed. 0 < amount <= held, now < captureDeadline. */
export interface CaptureRequest extends StateGuard {
  amount: bigint;
  /** true: return the uncaptured remainder to the payer in the same instruction (held -> 0). */
  releaseRemainder: boolean;
}

/** capture402 `void` (tag 3), merchant-signed. Returns everything still held to the payer. */
export type ReleaseRequest = StateGuard;

/**
 * capture402 `refund` (tag 4), merchant-signed. Paid from the MERCHANT's own token account,
 * 0 < amount <= refundable (captured, not yet refunded), now < refundDeadline.
 */
export interface RefundRequest extends StateGuard {
  amount: bigint;
}

export interface TxReceipt {
  /** Mock ref for MockBackend; finalized devnet transaction signature for Capture402Backend. */
  txSig: string;
}

/** Decoded capture402 Payment account (176 bytes, discriminator "SACPAY01"). */
export interface EscrowStatus {
  holdId: string;
  payer: string;
  payee: string;
  mint: string;
  maximum: bigint;
  /** Still locked in the vault. */
  held: bigint;
  /** Captured and not yet refunded. */
  refundable: bigint;
  captureDeadline: number;
  refundDeadline: number;
}

/**
 * A backend MUST await ctx.onPrepared(p) once it has built+signed the transaction (signature
 * and, for hold, the payment PDA known) and BEFORE it sends the transaction. The service uses
 * this to durably record the prepared tx (op.prepared) before the send, so that a lost response
 * after send can still be reconciled against on-chain truth via getTxOutcome.
 */
export interface PreparedTx {
  txSig: string;
  holdId?: string;
  lastValidBlockHeight?: number;
}

export interface SubmitContext {
  onPrepared?(p: PreparedTx): void | Promise<void>;
}

export interface TxOutcomeQuery {
  kind: "hold" | "capture" | "release" | "refund";
  txSig: string | null;
  holdId: string | null;
  payer: string;
  /** hold only: used to derive the payment PDA when txSig is unknown. */
  salt?: string;
  lastValidBlockHeight?: number;
}

export type TxOutcome =
  | { status: "executed"; txSig: string | null; holdId?: string }
  | { status: "failed"; code?: string }
  | { status: "not_found" }
  | { status: "pending" };

export interface PaymentBackend {
  readonly name: string;
  /** No capture402 instruction: mandates are off-chain. May no-op or persist/anchor terms. */
  createMandate(terms: MandateTerms): Promise<{ ref?: string }>;
  /** capture402 `authorize` (tag 0), payer-signed. */
  hold(req: HoldRequest, ctx?: SubmitContext): Promise<HoldReceipt>;
  /** capture402 `capture` (tag 2), merchant-signed. */
  capture(req: CaptureRequest, ctx?: SubmitContext): Promise<TxReceipt>;
  /** capture402 `void` (tag 3), merchant-signed. */
  release(req: ReleaseRequest, ctx?: SubmitContext): Promise<TxReceipt>;
  /** capture402 `refund` (tag 4), merchant-signed. */
  refund(req: RefundRequest, ctx?: SubmitContext): Promise<TxReceipt>;
  /** Read + decode the Payment account. null if it does not exist. */
  getStatus(holdId: string): Promise<EscrowStatus | null>;
  /**
   * Optional. Resolves whether a money-moving call actually executed on-chain, for reconciling
   * an UNKNOWN op after a lost response / BackendOutcomeUnknown. If absent, the service keeps
   * the reservation and stays UNKNOWN until an external reconcile or same-key retry supplies
   * evidence (signature status / account exists). Capture402Backend may omit this for now.
   */
  getTxOutcome?(q: TxOutcomeQuery): Promise<TxOutcome>;
}

/**
 * Thrown by backends. `code` mirrors capture402 facilitator reasons where possible, e.g.
 * "capture_deadline_expired". `phase: "confirmed_failure"` means the tx landed with an error
 * (definitely did not move funds as intended). For a possible send with unknown outcome the
 * backend MUST throw BackendOutcomeUnknown instead — never reclassify that as BackendError.
 */
export class BackendError extends Error {
  constructor(
    public readonly code: string,
    message: string,
    public readonly phase: "validation" | "confirmed_failure" = "validation",
    public readonly details?: { signature: string; transactionError: unknown },
  ) {
    super(message);
    this.name = "BackendError";
  }
}

/** Public reconciliation data; retain privately before reporting UNKNOWN. No secret key material. */
export interface UnknownOperation {
  readonly operation: "hold" | "capture" | "release" | "refund";
  readonly holdId: string;
  readonly salt?: string;
  readonly amount?: string;
  readonly expectedHeld?: string;
  readonly expectedRefundable?: string;
  readonly signature: string;
  readonly signedTransaction: string;
  readonly blockhash: string;
  readonly lastValidBlockHeight: string;
  readonly programId: string;
  readonly genesisHash: string;
  readonly abiCommit: string;
}

/** A possible send is not a proven failure. Intentionally separate from BackendError. */
export class BackendOutcomeUnknown extends Error {
  readonly code = "unknown_outcome";
  constructor(public readonly evidence: UnknownOperation) {
    super(
      "Transaction outcome UNKNOWN; retain original evidence and reservation, reconcile without retry",
    );
    this.name = "BackendOutcomeUnknown";
  }
}
